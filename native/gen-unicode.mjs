// Run with the grader's Node 22 from native/ to refresh unicode.inc.
// Slugs observe three outcomes after NFKD: ASCII alphanumerics, a
// separator, or nothing. Canonical reordering moves only dropped marks.
const mark = /^\p{M}$/u;
const keep = /^[A-Za-z0-9]$/;
const ranges = [];
const mappings = [];
let data = '';

for (let cp = 128; cp <= 0x10ffff; cp++) {
  const char = String.fromCodePoint(cp);
  let projected = '';
  for (const part of char.normalize('NFKD')) {
    if (keep.test(part)) projected += part;
    else if (!mark.test(part) && !projected.endsWith('-')) projected += '-';
  }
  if (projected === '-') continue;
  if (projected === '') {
    const last = ranges.at(-1);
    if (last && last[1] + 1 === cp) last[1] = cp;
    else ranges.push([cp, cp]);
  } else {
    mappings.push([cp, data.length, projected.length]);
    data += projected;
  }
}

// The generated mapping keys currently fit 17 bits. Keep the lower 15 bits
// for a 12-bit pool offset and a 3-bit length.
const dropWords = ranges.map(([first, last]) => {
  if (last - first > 255) throw new Error('slug drop range exceeds 256 code points');
  return first * 256 + last - first;
});
const mapWords = mappings.map(([cp, offset, length]) => {
  if (cp >= 2 ** 17 || offset >= 2 ** 12 || length > 7) {
    throw new Error('slug mapping outgrows its packed entry');
  }
  return cp * 32768 + offset * 8 + length;
});
const rows = (items) => {
  const lines = [];
  for (let i = 0; i < items.length; i += 8) {
    const words = items.slice(i, i + 8).map((word) => '0x' + word.toString(16));
    lines.push('    ' + words.join(', ') + ',');
  }
  return lines.join('\n');
};
const literals = data.match(/.{1,88}/g).map(JSON.stringify).join('\n    ');

console.log(`/* Generated by gen-unicode.mjs using Unicode ${process.versions.unicode}. */
static const uint slug_drops[] = {
${rows(dropWords)}
};
static const uint slug_maps[] = {
${rows(mapWords)}
};
static const char slug_data[] =
    ${literals};`);
